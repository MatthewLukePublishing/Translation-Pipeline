import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import AdmZip from "adm-zip";
import XLSX, { restoreLiteralCells } from "../../Code/SheetJsNode.mjs";
import atomicFiles from "../../Code/AtomicFiles.cjs";
import { CONTENT_EXPORT_HEADERS, assertLiteralXlsxWorkbook } from "./WorkbookContract.mjs";
import { indexIcml, sha256, verifySourcePackage } from "./SourcePackage.mjs";

const root = path.resolve(process.argv[2] || "");
if (!process.argv[2]) throw new Error("Supply the exported source package directory.");
const manifestPath = path.join(root, "source_package.json");
const record = JSON.parse(fs.readFileSync(manifestPath, "utf8").replace(/^\uFEFF/, ""));
if (record.status !== "exported" || record.schemaVersion !== 1) throw new Error("Source package is not ready for indexing.");
if (sha256(record.originalDocument) !== record.originalDocumentSha256) throw new Error("Original source changed during export.");
const textRoot = path.join(root, "Text");
const files = fs.readdirSync(textRoot).filter(name => /\.icml$/i.test(name)).sort((a, b) => {
  const page = name => Number(name.match(/Page_(\d+)/)?.[1] || 999999);
  return page(a) - page(b) || a.localeCompare(b);
});
if (files.length !== record.storyCount || !files.length || files.length > 5000) throw new Error("Exported story count mismatch.");
const rows = [[...CONTENT_EXPORT_HEADERS]];
const counters = { paragraph: 0, content: 0 };
for (const name of files) {
  const file = path.join(textRoot, name);
  const indexed = indexIcml(fs.readFileSync(file, "utf8").replace(/^\uFEFF/, ""), counters);
  rows.push(...indexed.rows);
  atomicFiles.writeFileAtomicSync(file, indexed.text, "utf8");
}
const modules = process.env.CODEX_ARTIFACT_NODE_MODULES;
if (!modules) throw new Error("CODEX_ARTIFACT_NODE_MODULES is required.");
const requireRuntime = createRequire(path.join(modules, "package.json"));
const { Workbook, SpreadsheetFile } = requireRuntime("@oai/artifact-tool");
const workbook = Workbook.create();
const sheet = workbook.worksheets.add("Content");
sheet.showGridLines = false;
const range = sheet.getRange(`A1:D${rows.length}`);
range.setNumberFormat("@");
range.values = rows.map(row => row.map(value => value.startsWith("=") ? "'" + value : value));
range.format.font = { name: "Arial", size: 10 };
range.format.verticalAlignment = "top";
range.format.wrapText = true;
sheet.getRange("A1:D1").format.fill = "#24364B";
sheet.getRange("A1:D1").format.font = { name: "Arial", size: 10, color: "#FFFFFF", bold: true };
sheet.getRange(`A1:A${rows.length}`).format.columnWidth = 22;
sheet.getRange(`B1:B${rows.length}`).format.columnWidth = 95;
sheet.getRange(`C1:C${rows.length}`).format.columnWidth = 15;
sheet.getRange(`D1:D${rows.length}`).format.columnWidth = 95;
sheet.freezePanes.freezeRows(1);
workbook.recalculate();
const output = path.join(root, "content_export.xlsx");
await (await SpreadsheetFile.exportXlsx(workbook)).save(output);
const serialized = XLSX.readFile(output, { cellStyles: true });
restoreLiteralCells(serialized.Sheets[serialized.SheetNames[0]], rows);
XLSX.writeFile(serialized, output, { bookSST: true, compression: true, cellStyles: true });
const roundTrip = XLSX.readFile(output, { cellFormula: true, cellText: false });
const { worksheet } = assertLiteralXlsxWorkbook(roundTrip, output);
const recovered = XLSX.utils.sheet_to_json(worksheet, { header: 1, defval: "", raw: true });
if (JSON.stringify(recovered) !== JSON.stringify(rows)) throw new Error("Source workbook literal round-trip changed content.");
const preview = await workbook.render({ sheetName: "Content", range: "A1:D9", scale: 1, format: "png" });
fs.writeFileSync(path.join(root, "content_export_preview.png"), Buffer.from(await preview.arrayBuffer()));
const archive = new AdmZip();
for (const name of files) archive.addLocalFile(path.join(textRoot, name), "Text");
archive.writeZip(path.join(root, "Text.zip"));
record.status = "complete";
record.completedAt = new Date().toISOString();
record.dataRows = rows.length - 1;
record.paragraphs = counters.paragraph;
record.files = [record.document, "content_export.xlsx", "Text.zip", ...files.map(name => `Text/${name}`)]
  .map(name => ({ path: name, sha256: sha256(path.join(root, name)) }));
atomicFiles.writeJsonAtomicSync(manifestPath, record, { trailingNewline: true });
verifySourcePackage(root);
console.log(`CURRENT_SOURCE_PACKAGE_READY|stories=${files.length}|rows=${rows.length - 1}|package=${root}`);
